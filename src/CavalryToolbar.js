    function stateIssueFor(raw) {
        if (raw === null || typeof raw === "undefined") return "";
        if (!raw || typeof raw !== "object") return "配置内容损坏；当前版本只读，未写回。";
        if (!isInteger(raw.version)) return "配置版本无效；当前版本只读，未写回。";
        if (raw.version > SCHEMA_VERSION) return "检测到较新的配置格式 v" + raw.version + "；当前版本只读，未写回。";
        if (raw.version < SCHEMA_VERSION) return "检测到不受支持的配置格式 v" + raw.version + "；当前版本只读，未写回。";
        if (!Array.isArray(raw.profiles) || !raw.profiles.length || raw.profiles.length > 20)
            return "配置内容损坏；当前版本只读，未写回。";
        for (var i = 0; i < raw.profiles.length; i++) {
            var profile = raw.profiles[i];
            if (!profile || typeof profile !== "object" || !Array.isArray(profile.slots))
                return "配置内容损坏；当前版本只读，未写回。";
            if (profile.modes !== null && typeof profile.modes !== "undefined" && !Array.isArray(profile.modes))
                return "配置内容损坏；当前版本只读，未写回。";
        }
        if (raw.custom !== null && typeof raw.custom !== "undefined" && !Array.isArray(raw.custom))
            return "配置内容损坏；当前版本只读，未写回。";
        return "";
    }
    function normalise(raw) {
        var out = { version: SCHEMA_VERSION, active: 0, profiles: [emptyProfile("工作台")], custom: [], reducedMotion: false };
        if (!raw || raw.version !== SCHEMA_VERSION || !Array.isArray(raw.profiles) || !raw.profiles.length) return out;
        out.reducedMotion = raw.reducedMotion === true;
        out.profiles = raw.profiles.slice(0, 20).map(function (profile) {
            profile = profile && typeof profile === "object" ? profile : {};
            var result = emptyProfile(typeof profile.name === "string" ? truncate(trimText(profile.name), 32) : "工作台");
            if (!result.name) result.name = "工作台";
            if (Array.isArray(profile.slots)) {
                for (var i = 0; i < COUNT; i++) {
                    var path = cleanPath(profile.slots[i]);
                    result.slots[i] = isScript(path) ? path : "";
                    result.modes[i] = Array.isArray(profile.modes) && profile.modes[i] === "ui" ? "ui" : "script";
                }
            }
            return result;
        });
        if (isInteger(raw.active) && raw.active >= 0 && raw.active < out.profiles.length) out.active = raw.active;
        if (Array.isArray(raw.custom)) {
            out.custom = raw.custom.map(cleanPath).filter(isScript).slice(0, 200);
        }
        return out;
    }
    function slotAt(position) {
        var dx = position.x - MID, dy = position.y - MID;
        var radius = Math.sqrt(dx * dx + dy * dy);
        if (radius < 68 || radius > 152) return -1;
        return Math.floor((((90 - Math.atan2(dy, dx) * 180 / Math.PI) + 360) % 360) / (360 / COUNT));
    }
