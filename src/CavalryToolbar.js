    // Hover and press share one bounded timer. No timer runs while the ring is at rest.
    // The cubic is the existing UI ease-out (0.23, 1, 0.32, 1), solved in x.
    function easeHover(progress) {
        if (progress <= 0 || progress >= 1) return progress;
        var low = 0, high = 1, t = 0, x = 0;
        for (var i = 0; i < 14; i++) {
            t = (low + high) / 2;
            x = 3 * (1 - t) * (1 - t) * t * 0.23 + 3 * (1 - t) * t * t * 0.32 + t * t * t;
            if (x < progress) low = t; else high = t;
        }
        return 1 - Math.pow(1 - t, 3);
    }
    function finishMotion() {
        if (motionTimer) motionTimer.stop();
        pulseValue = 0;
        for (var i = 0; i < COUNT; i++) {
            hoverValues[i] = i === hoveredSlot ? 1 : 0;
            pressValues[i] = i === pressedSlot ? 1 : 0;
        }
        drawDonut();
    }
    function tickMotion() {
        var now = Date.now();
        var hoverProgress = Math.min(1, Math.max(0, (now - motionStart) / HOVER_DURATION));
        var pressProgress = Math.min(1, Math.max(0, (now - pressStart) / PRESS_DURATION));
        var pulseProgress = Math.min(1, Math.max(0, (now - pulseStart) / PULSE_DURATION));
        var hoverEased = easeHover(hoverProgress), pressEased = easeHover(pressProgress);
        pulseValue = pulseProgress >= 1 ? 0 : pulseProgress < 0.5 ? easeHover(pulseProgress * 2) : easeHover((1 - pulseProgress) * 2);
        for (var i = 0; i < COUNT; i++) {
            var hoverTarget = i === hoveredSlot ? 1 : 0, pressTarget = i === pressedSlot ? 1 : 0;
            hoverValues[i] = hoverFrom[i] + (hoverTarget - hoverFrom[i]) * hoverEased;
            pressValues[i] = pressFrom[i] + (pressTarget - pressFrom[i]) * pressEased;
        }
        if (hoverProgress >= 1 && pressProgress >= 1 && pulseProgress >= 1) finishMotion(); else drawDonut();
    }
    function startMotion() {
        if (state.reducedMotion || !motionAvailable) { finishMotion(); return; }
        try {
            if (!motionTimer) {
                motionTimer = new api.Timer({ onTimeout: tickMotion });
                motionTimer.setInterval(16); motionTimer.setRepeating(true);
            }
            motionTimer.start(); drawDonut();
        } catch (error) {
            motionAvailable = false;
            if (motionButton) { motionButton.setText("动效：静态"); motionButton.setEnabled(false); }
            finishMotion();
        }
    }
    function settleMotion() {
        // Retarget from the current presentation, including an interrupted transition.
        if (motionTimer && motionTimer.isActive()) tickMotion();
    }
