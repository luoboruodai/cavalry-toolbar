        function setValue(index) {
            selected = index >= 0 && index < entries.length ? index : -1;
            display(selected >= 0 ? entries[selected] : "");
        }
        widget.addEntry = function (text) { entries.push(String(text)); };
        widget.clear = function () { entries = []; selected = -1; display(""); };
        widget.getValue = function () { return selected; };
