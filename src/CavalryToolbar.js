    function ringText(name, fallback) {
        // Path.addText has no font selection/fallback API; native labels keep the full Unicode name.
        return /[^\x20-\x7e]/.test(name) ? fallback : name;
    }
    function centeredRingText(text, size, x, y, color, maxWidth, pulseScale) {
        var shape = new cavalry.Path(); shape.addText(text, size, 0, 0);
        if (typeof shape.boundingBox === "function" && typeof shape.translate === "function") {
            var box = shape.boundingBox();
            if (maxWidth && box.width > maxWidth && typeof shape.scale === "function") {
                var scale = maxWidth / box.width; shape.scale(scale, scale); box = shape.boundingBox();
            }
            if (pulseScale && pulseScale !== 1 && typeof shape.scale === "function") {
                shape.scale(pulseScale, pulseScale); box = shape.boundingBox();
            }
            shape.translate(x - box.centre.x, y - box.centre.y);
            draw.addPath(shape.toObject(), { color: color });
        } else textOnDonut(text, size, x - text.length * size * 0.25, y, color);
    }
    function ringArcLayout(index, count) {
        var n = Math.max(1, count), step = Math.PI * 2 / n;
        return {
            middle: Math.PI / 2 - step * (index + 0.5), angleStep: step,
            metaRadius: n >= 10 ? 74 : 80, nameRadii: n >= 10 ? [84, 98, 112, 126] : [90, 110, 128],
            maxNameWidth: (n >= 10 ? 126 : 128) * Math.max(0.1, step - 0.06),
            metaSize: n >= 10 ? 8 : 9,
            nameSize: n >= 10 ? 8 : n >= 5 ? 9 : 10
        };
    }
    function arcRingText(text, size, x, y, radius, middle, color, maxWidth) {
        var chars = String(text).split(""), widths = chars.map(function (char) { return measureRingText(char, size); });
        if (!chars.length || radius <= 0 || maxWidth <= 0) return;
        var rawTotal = widths.reduce(function (sum, width) { return sum + width; }, 0);
        var fit = Math.min(1, maxWidth / Math.max(rawTotal, 0.001)), total = rawTotal * fit;
        var direction = Math.sin(middle) >= 0 ? -1 : 1;
        var start = direction < 0 ? middle + total / (2 * radius) : middle - total / (2 * radius), travelled = 0;
        chars.forEach(function (char, index) {
            var width = widths[index] * fit;
            var theta = start + direction * (travelled + width / 2) / radius;
            var px = x + Math.cos(theta) * radius, py = y + Math.sin(theta) * radius;
            var rotation = (direction < 0 ? theta - Math.PI / 2 : theta + Math.PI / 2) * 180 / Math.PI;
            var shape = new cavalry.Path(); shape.addText(char, size, 0, 0);
            if (typeof shape.boundingBox === "function" && typeof shape.translate === "function") {
                var box = shape.boundingBox();
                shape.translate(-box.centre.x, -box.centre.y);
                if (fit < 1 && typeof shape.scale === "function") shape.scale(fit, fit);
                if (typeof shape.rotate === "function") shape.rotate(rotation);
                shape.translate(px, py);
                draw.addPath(shape.toObject(), { color: color });
            } else textOnDonut(char, size, px, py, color);
            travelled += width;
        });
    }
    function measureRingText(text, size) {
        var shape = new cavalry.Path(); shape.addText(text, size, 0, 0);
        if (typeof shape.boundingBox === "function") return shape.boundingBox().width;
        return text.length * size * 0.52;
    }
    function ringNameLines(text, size, maxWidth, maxLines) {
        var chars = String(text).split(""), lines = [], start = 0;
        if (!chars.length) return [""];
        while (start < chars.length && lines.length < maxLines) {
            var end = start, lastBreak = -1, overflow = false;
            while (end < chars.length) {
                var candidate = chars.slice(start, end + 1).join("");
                if (measureRingText(candidate, size) > maxWidth && end > start) {
                    var split = lastBreak > start ? lastBreak : end;
                    lines.push(chars.slice(start, split).join(""));
                    start = split; overflow = true; break;
                }
                end++;
                if (end > start && (chars[end - 1] === "-" || chars[end - 1] === "_" || chars[end - 1] === " ")) lastBreak = end;
            }
            if (!overflow) {
                if (end > start) { lines.push(chars.slice(start, end).join("")); start = end; }
                else { lines.push(chars[start]); start++; }
            }
        }
        if (start < chars.length && lines.length) {
            var last = lines.pop();
            while (last && measureRingText(last + "…", size) > maxWidth) last = last.slice(0, -1);
            lines.push(last + "…");
        }
        return lines;
    }
    function mixColor(from, to, amount) {
        var t = Math.min(1, Math.max(0, amount));
        if (t === 0) return from;
        if (t === 1) return to;
        var a = parseInt(from.slice(1), 16), b = parseInt(to.slice(1), 16);
        function channel(shift) { return Math.round(((a >> shift) & 255) + (((b >> shift) & 255) - ((a >> shift) & 255)) * t); }
        return "#" + ((1 << 24) + (channel(16) << 16) + (channel(8) << 8) + channel(0)).toString(16).slice(1);
    }
    function drawDonut() {
        if (!draw) return;
        draw.clearPaths();
        var slots = activeProfile().slots, step = Math.PI * 2 / COUNT;
        for (var i = 0; i < COUNT; i++) {
            var t = Math.PI / 2 - step * (i + 0.5);
            var lift = state.reducedMotion || !motionAvailable ? 0 : hoverValues[i] * HOVER_OFFSET - pressValues[i] * PRESS_OFFSET;
            var ox = Math.cos(t) * lift, oy = Math.sin(t) * lift;
            var points = [], a;
            for (var j = 0; j <= 8; j++) {
                a = Math.PI / 2 - step * (i + j / 8) - 0.012 + 0.024 * (j / 8);
                points.push([MID + Math.cos(a) * 144 + ox, MID + Math.sin(a) * 144 + oy]);
            }
            for (j = 8; j >= 0; j--) {
                a = Math.PI / 2 - step * (i + j / 8) - 0.012 + 0.024 * (j / 8);
                points.push([MID + Math.cos(a) * 70 + ox, MID + Math.sin(a) * 70 + oy]);
            }
            var restColor = i === chosenSlot ? C.selected : (slots[i] ? C.raised : C.surface);
            var color = mixColor(restColor, i === chosenSlot ? C.green : C.selected, hoverValues[i]);
            if (pressValues[i] > 0) color = mixColor(color, C.bg, pressValues[i] * 0.25);
            if (dragState && dragState.active && i === dragState.index) color = C.panel;
            polygon(points, color, false);
            if (dragState && dragState.active && i === hoveredSlot && i !== dragState.index)
                polygon(points, C.bright, true);
            var number = (i + 1 < 10 ? "0" : "") + (i + 1);
            var layout = ringArcLayout(i, COUNT);
            var x = MID + ox, y = MID + oy;
            if (slots[i]) {
                var meta = number + " · " + (activeProfile().modes[i] === "ui" ? "UI" : "JS");
                arcRingText(meta, layout.metaSize, x, y, layout.metaRadius, t,
                    i === chosenSlot ? (hoverValues[i] > 0.05 ? "#ffffff" : C.bright) : C.muted,
                    layout.metaRadius * Math.max(0.1, layout.angleStep - 0.06));
                var name = ringText(fileName(slots[i]), activeProfile().modes[i] === "ui" ? "UI" : "JS");
                var lines = ringNameLines(name, layout.nameSize, layout.maxNameWidth, COUNT >= 10 ? 4 : 2);
                var radii = lines.length === 1 ? [114] : layout.nameRadii.slice(-lines.length);
                for (var lineIndex = 0; lineIndex < lines.length; lineIndex++)
                    arcRingText(lines[lineIndex], layout.nameSize, x, y, radii[lineIndex], t,
                        i === chosenSlot && hoverValues[i] > 0.05 ? "#ffffff" : C.text, radii[lineIndex] * Math.max(0.1, layout.angleStep - 0.06));
            } else {
                arcRingText(number, 13, x, y, 108, t, C.muted, 2 * 108 * Math.sin(layout.angleStep / 2) - 8);
            }
        }
        var pulseScale = state.reducedMotion || !motionAvailable ? 1 : 1 + pulseValue * 0.06;
        var hub = new cavalry.Path(); hub.addEllipse(MID, MID, 64 * pulseScale, 64 * pulseScale);
        draw.addPath(hub.toObject(), { color: C.panel });
        var focus = hoveredSlot >= 0 ? hoveredSlot : chosenSlot;
        // Match the native wheel: the hub carries slot/profile state, while each
        // sector owns its script name. The full selected name remains below the preview.
        var hubTitle = slots[focus] ? ((focus + 1 < 10 ? "0" : "") + (focus + 1)) : activeProfile().name;
        centeredRingText(truncate(ringText(hubTitle, "QUICKBAR"), 12), slots[focus] ? 18 : 13, MID, MID + 8, C.text, 105, pulseScale);
        var caption = dragState && dragState.active ? "DROP TO SWAP" : slots.filter(Boolean).length + " / 12";
        centeredRingText(caption, 11, MID, MID - 12, C.bright, 105, pulseScale);
        draw.redraw();
    }

