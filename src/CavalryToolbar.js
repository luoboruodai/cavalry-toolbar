    function storePath(path) {
        path = cleanPath(path);
        if (!path || !rootPath || path.indexOf("@scripts/") === 0) return path;
        var root = rootPath.replace(/\/+$/, "");
        var lowerPath = path.toLowerCase(), lowerRoot = root.toLowerCase();
        if (lowerPath === lowerRoot) return "@scripts";
        if (lowerPath.indexOf(lowerRoot + "/") === 0) return "@scripts/" + path.slice(root.length + 1);
        return path;
    }

