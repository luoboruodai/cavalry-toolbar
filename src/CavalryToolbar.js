    function addPath(path) {
        path = resolvePath(path);
        if (!isScript(path) || (path === selfPath || path === rootPath + "/CavalryQuickbarPanel.js")) return false;
        if (catalogue.indexOf(path) === -1) catalogue.push(path);
        return true;
    }
    function scanScripts() {
        catalogue = [];
        state.custom.forEach(addPath);
        state.profiles.forEach(function (profile) { profile.slots.forEach(addPath); });
        if (!rootPath) return;
        try {
            var roots = [rootPath], children = [], i, j, list;
            for (i = 0; i < roots.length && i < 40; i++) {
                list = typeof api.listDirectoryPaths === "function" ? api.listDirectoryPaths(roots[i], true) : api.listDirectory(roots[i]);
                if (!Array.isArray(list)) continue;
                for (j = 0; j < list.length && j < 600; j++) {
                    var path = cleanPath(list[j]);
                    if (path.indexOf("/") < 0) path = roots[i] + "/" + path;
                    if (/_assets$/i.test(path) || path.indexOf("/" + LAUNCHER_FOLDER + "/") >= 0) continue;
                    if (isScript(path)) addPath(path);
                    else if (roots.length < 40 && typeof api.isDirectory === "function" && api.isDirectory(path)) children.push(path);
                }
                if (i === 0) roots = roots.concat(children.slice(0, 39));
            }
        } catch (error) { console.log("Cavalry Toolbar: scan unavailable: " + error); }
        catalogue.sort(function (a, b) { var left = fileName(a).toLowerCase(), right = fileName(b).toLowerCase(); return left < right ? -1 : (left > right ? 1 : 0); });
    }
