    function importProfiles() {
        if (!canMutate()) return false;
        if (typeof api.presentOpenFile !== "function") {
            say("当前 Cavalry 没有可用的配置读取接口。", true);
            return false;
        }
        var chosen = api.presentOpenFile(rootPath || "", "导入 Cavalry Toolbar 配置", "JSON (*.json)");
        if (!chosen) return false;
        try {
            var parsed = JSON.parse(readText(cleanPath(chosen)));
            var incoming = parsed && parsed.format === "com.cavalrytoolbar.profile-export" ? parsed.state : parsed;
            var issue = stateIssueFor(incoming);
            if (issue) { say("配置导入失败：" + issue, true); return false; }
            var previous = state;
            state = normalise(incoming);
            refreshProfiles(); scanScripts(); refreshLibrary();
            if (save()) {
                say("已导入配置：" + fileName(chosen));
                return true;
            }
            state = previous; refreshProfiles(); scanScripts(); refreshLibrary();
            return false;
        } catch (error) {
            say("配置导入失败：" + error, true);
            return false;
        }
    }
